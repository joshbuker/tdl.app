// Bundles drizzle-kit's migrations into src/migrations.generated.ts, so devices can apply them
// without reading files. Run with `pnpm --filter @tdl/device-store bundle-migrations`.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

export interface Migration {
  tag: string;
  sql: string;
}

/** Each `<tag>/migration.sql` in the folder, oldest first (drizzle-kit's tags start with a timestamp). */
export function readMigrations(folder: string): Migration[] {
  return readdirSync(folder, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort()
    .map((tag) => ({ tag, sql: readFileSync(join(folder, tag, 'migration.sql'), 'utf8') }));
}

export function renderMigrations(migrations: Migration[]): string {
  const entries = migrations.map((m) => `  {\n    tag: ${JSON.stringify(m.tag)},\n    sql: ${JSON.stringify(m.sql)},\n  },`);
  return [
    '// Generated by scripts/bundle-migrations.ts from drizzle/. Do not edit.',
    '',
    'export const migrations: { tag: string; sql: string }[] = [',
    ...entries,
    '];',
    '',
  ].join('\n');
}

if (import.meta.main) {
  const root = fileURLToPath(new URL('..', import.meta.url));
  writeFileSync(join(root, 'src/migrations.generated.ts'), renderMigrations(readMigrations(join(root, 'drizzle'))));
}
